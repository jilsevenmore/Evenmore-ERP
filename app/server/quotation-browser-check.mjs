import puppeteer from 'puppeteer-core';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createQuotationServer } from './quotation-server.mjs';

const directory = await mkdtemp(join(tmpdir(), 'quotation-browser-'));
const token = 'browser-test-only-'.repeat(4);
const server = await createQuotationServer({ file: join(directory, 'shares.json'), adminToken: token, publicOrigin: 'https://quotes.example.com' });
await new Promise(resolve => server.listen(8787, '127.0.0.1', resolve));
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const errors = [];
const page = await browser.newPage();
page.on('pageerror', error => errors.push(error.message));
const click = async text => {
  await page.waitForFunction(value => [...document.querySelectorAll('button')].some(button => (button.getAttribute('aria-label') || button.textContent.trim()) === value), {}, text);
  await page.evaluate(value => [...document.querySelectorAll('button')].find(button => (button.getAttribute('aria-label') || button.textContent.trim()) === value).click(), text);
};
const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('horizon_erp_v2_state')));
try {
  await page.goto('http://127.0.0.1:5173/sales/quotations');
  await page.waitForFunction(() => localStorage.getItem('horizon_erp_v2_state'));
  await page.evaluate(token => {
    sessionStorage.setItem('quotation_admin_token', token);
    const state = JSON.parse(localStorage.getItem('horizon_erp_v2_state'));
    state.quotations.unshift({ id: 'q-browser', quoteNumber: 'Q-BROWSER', date: '17/09/2026', validUntil: '30 days', customer: 'Browser Customer', status: 'Draft', amount: 216, items: [{ id: 'test-item', name: 'Test product', description: 'Test product', qty: 2, rate: 100, discount: 10, tax: 20, amount: 216 }] });
    localStorage.setItem('horizon_erp_v2_state', JSON.stringify(state));
  }, token);
  await page.reload();
  await click('Q-BROWSER');
  await click('Share Quotation');
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Generate Link')?.disabled);
  await page.evaluate(() => [...document.querySelectorAll('label')].find(l => l.textContent.includes('Allow customer acceptance')).querySelector('input').click());
  await click('Generate Link');
  await page.waitForSelector('img[alt="Scan to open this quotation"]');
  let saved = await state();
  let quote = saved.quotations.find(q => q.id === 'q-browser');
  assert.equal(quote.status, 'Draft');
  assert.ok(quote.share.url.startsWith('https://quotes.example.com/quote/Q-BROWSER/'));
  await page.evaluate(() => [...document.querySelectorAll('[role="dialog"] button')].find(b => b.textContent.trim() === 'Close').click());
  await click('Send');
  assert.ok(await page.evaluate(() => document.body.textContent.includes('Email and WhatsApp delivery are not connected')));
  await page.evaluate(() => [...document.querySelectorAll('[role="dialog"] button')].find(b => b.textContent.trim() === 'Close').click());
  const context = await browser.createBrowserContext();
  const customer = await context.newPage();
  customer.on('pageerror', error => errors.push(error.message));
  await customer.goto('http://127.0.0.1:5173' + new URL(quote.share.url).pathname);
  await customer.waitForSelector('.printable-document');
  assert.ok(await customer.evaluate(() => document.body.textContent.includes('Browser Customer')));
  assert.equal(await customer.$('aside'), null);
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('horizon_erp_v2_state')).quotations.find(q => q.id === 'q-browser').status === 'Viewed', { timeout: 25000 });
  await customer.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Accept Quote').click());
  await customer.evaluate(() => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === 'Confirm Acceptance').click());
  await customer.waitForFunction(() => document.body.textContent.includes('Quotation accepted'));
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('horizon_erp_v2_state')).quotations.find(q => q.id === 'q-browser').status === 'Accepted', { timeout: 25000 });
  await page.setViewport({ width: 1440, height: 1100 });
  await page.screenshot({ path: join(tmpdir(), 'evenmore-quotation-ui.png') });
  await click('Download PDF');
  await page.waitForSelector('[aria-label="Quotation PDF preview"]');
  const pdf = await page.pdf({ format: 'A4' });
  assert.ok(pdf.length > 1000);
  await page.click('[aria-label="Close preview"]');
  const before = await state();
  await click('Convert to Delivery Challan');
  await click('Create Delivery Challan');
  await page.waitForFunction(() => location.pathname === '/sales/delivery');
  await click('Prepare Dispatch');
  await page.waitForFunction(() => document.body.textContent.includes('Issue Warehouse Delivery Challan'));
  const after = await state();
  const challan = after.deliveryChallans.find(dc => dc.sourceQuotationId === 'q-browser');
  assert.equal(challan.status, 'Draft');
  assert.equal(challan.items.length, 1);
  assert.equal(challan.salesOrderNumber, '');
  assert.deepEqual(after.inventoryMovements, before.inventoryMovements);
  await click('Dispatch & Generate Waybill');
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('horizon_erp_v2_state')).deliveryChallans.find(dc => dc.sourceQuotationId === 'q-browser').status === 'In Transit');
  const dispatched = await state();
  assert.equal(dispatched.deliveryChallans.filter(dc => dc.sourceQuotationId === 'q-browser').length, 1);
  assert.equal(dispatched.inventoryMovements.length, before.inventoryMovements.length + 1);
  await page.goto('http://127.0.0.1:5173/sales/quotations');
  await click('Q-BROWSER');
  await click('Open Delivery Challan');
  await page.waitForFunction(() => location.pathname === '/sales/delivery');
  assert.equal((await state()).deliveryChallans.filter(dc => dc.sourceQuotationId === 'q-browser').length, 1);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('PASS: share and QR, honest send dialog, customer view in separate browser context, automatic Viewed sync, PDF rendering, linked draft conversion, stock posting on dispatch, and repeat conversion without duplicates.');
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
  await rm(directory, { recursive: true, force: true });
}
